"""П8: Автозапуск при старте Windows.

Seam:
  default_startup_dir() -> str
  install_startup(target_script, config_path, pythonw=None, startup_dir=None) -> Path
  uninstall_startup(target_script, startup_dir=None) -> bool

Реализация: создаёт .vbs-лаунчер в папке Startup (shell:startup), который запускает
`pythonw <target_script> --config <config_path>` без консольного окна.
startup_dir параметризуется для тестов (tmp_path), по умолчанию = реальная папка Startup.
Idempotent: повторный install перезаписывает тот же файл, без дубликатов.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path


def default_startup_dir() -> str:
    """Папка Startup текущего пользователя: %APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup"""
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("APPDATA env var is not set")
    return str(Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup")


def _launcher_name(target_script: str) -> str:
    base = Path(target_script).stem or "netmonitor"
    return f"netmonitor_{base}.vbs"


def _resolve_pythonw(pythonw: str | None) -> str:
    if pythonw:
        return pythonw
    # pythonw.exe рядом с текущим интерпретатором
    exe_dir = Path(sys.executable).parent
    pythonw_exe = exe_dir / "pythonw.exe"
    if pythonw_exe.exists():
        return str(pythonw_exe)
    # fallback — обычный python
    return sys.executable


def _vbs_content(pythonw: str, target_script: str, config_path: str) -> str:
    # VBScript: запустить процесс без окна (0 = hidden window)
    #_cmd = f'"{pythonw}" "{target_script}" --config "{config_path}"'
    return (
        "' Auto-generated by netmonitor. Do not edit manually.\n"
        f"' Launches: {pythonw} {target_script} --config {config_path}\n"
        'Set sh = CreateObject("WScript.Shell")\n'
        f'cmd = "{pythonw} ""{target_script}"" --config ""{config_path}"" "\n'
        'sh.Run cmd, 0, False\n'
    )


def install_startup(
    target_script: str,
    config_path: str,
    pythonw: str | None = None,
    startup_dir: str | None = None,
) -> Path:
    """Создать/обновить .vbs-лаунчер в папке Startup. Возвращает путь к файлу."""
    sdir = Path(startup_dir) if startup_dir else Path(default_startup_dir())
    sdir.mkdir(parents=True, exist_ok=True)

    launcher = sdir / _launcher_name(target_script)
    pw = _resolve_pythonw(pythonw)
    content = _vbs_content(pw, target_script, config_path)
    launcher.write_text(content, encoding="utf-8")
    return launcher


def uninstall_startup(target_script: str, startup_dir: str | None = None) -> bool:
    """Удалить лаунчер, если существует. True если был удалён, False если не было."""
    sdir = Path(startup_dir) if startup_dir else Path(default_startup_dir())
    launcher = sdir / _launcher_name(target_script)
    if launcher.exists():
        launcher.unlink()
        return True
    return False
